function inferCategory(coho: string, vi: string): DictionaryEntry['category'] {
  const text = `${coho} ${vi}`.toLowerCase();
  if (
    /(văn hoá|lễ hội|chiêng|cồng|tổ quốc|đất nước|dân làng|đồng bào|lịch sử|anh hùng|gương sáng|tục lệ|quy ước|thầy mo|người cil|dân tộc|bỏ mả|khố)/.test(
      text
    )
  ) {
    return 'culture';
  }
  if (
    /(học sinh|bài|lớp|phòng|viết|đọc|nghe|phấn|cái bàn|ghế|sách|trường|giáo dục|dạy|số |đếm|ký tên|biên bản|tiến bộ)/.test(
      text
    )
  ) {
    return 'school';
  }
  if (
    /(mẹ|cha|con |anh|chị|vợ|chồng|gia đình|bạn bè|cụ già|già làng|bác sĩ|mày|tôi|họ|chúng tôi|bàn tay|bàn chân|đầu|mũi|cổ|bụng|gan|phổi|lưỡi|trán|răng|đau|bệnh|sốt)/.test(
      text
    )
  ) {
    return 'family';
  }
  if (
    /(con |cá|tôm|cọp|gấu|nai|bò|khỉ|vịt|dê|gà|rắn|đỉa|trăn|heo|lươn|kền kền|núi|rừng|sông|biển|suối|thác|mặt trời|mặt trăng|hoa|cây|lá|tre|màu |mưa|bão|gió|cát|đất|khoai|chuối|chè)/.test(
      text
    )
  ) {
    return 'nature';
  }
  return 'daily';
}

function inferLevel(coho: string): 1 | 2 | 3 | 4 | 5 {
  const words = coho.trim().split(/\s+/).length;
  if (words >= 3) return 4;
  if (words === 2) return 3;
  if (coho.length <= 3) return 1;
  if (coho.length <= 5) return 2;
  return 3;
}

function buildExcelDictionary(): DictionaryEntry[] {
  const seen = new Set<string>();
  const entries: DictionaryEntry[] = [];

  for (const [cohoRaw, viRaw] of RAW_EXCEL_ROWS) {
    const coho = cohoRaw.trim();
    const vietnamese = viRaw.trim();
    const dedupeKey = `${coho.toLowerCase()}::${vietnamese.toLowerCase()}`;
    if (seen.has(dedupeKey)) continue;
    seen.add(dedupeKey);

    const featured = FEATURED_METADATA[coho];
    entries.push({
      coho,
      vietnamese,
      category: featured?.category ?? inferCategory(coho, vietnamese),
      level: featured?.level ?? inferLevel(coho),
      phonetic: featured?.phonetic,
      partOfSpeech: featured?.partOfSpeech,
      explanationVi: featured?.explanationVi,
      explanationKoho: featured?.explanationKoho,
      exampleKoho: featured?.exampleKoho,
      exampleVi: featured?.exampleVi,
      source: 'user_excel',
    });
  }

  return entries;
}

export const USER_EXCEL_DICTIONARY: DictionaryEntry[] = buildExcelDictionary();
